/** Every scroll target on the page. `hero` is the desktop, the rest are OS windows. */
export type SectionId = 'hero' | 'about' | 'experience' | 'skills' | 'projects' | 'contact'

/** Sections that render as content windows (everything but the hero). */
export type ContentSectionId = Exclude<SectionId, 'hero'>

/** Theme role a piece of content is tinted with; resolves to the active palette. */
export type AccentToken = 'primary' | 'secondary' | 'accent'

export type IconName =
  'user' | 'log' | 'chip' | 'grid' | 'mail' | 'download' | 'terminal' | 'crt' | 'close' | 'external'

export interface SectionMeta {
  id: ContentSectionId
  number: string
  title: string
  /** Pseudo file name shown in the window title bar, e.g. `about.md`. */
  file: string
  /** Status label shown in the title bar, e.g. `RO`. */
  status: string
  blurb: string
  icon: IconName
}

export interface BootLine {
  text: string
  /** Right-aligned status tag, e.g. `OK`. */
  status?: string
}

export interface SiteConfig {
  name: string
  shortName: string
  osName: string
  role: string
  tagline: string
  description: string
  url: string
  email: string
  phone: string
  location: { locality: string; region: string; country: string }
  resumePath: string
  resumeFileName: string
  ogImage: string
}

export interface Social {
  id: string
  label: string
  href: string
  handle: string
}

export interface Education {
  degree: string
  school: string
  period: string
  result: string
}

export interface Certification {
  name: string
  issuer: string
  year: string
}

export interface AboutContent {
  summary: string[]
  facts: { label: string; value: string }[]
  education: Education[]
  certifications: Certification[]
}

export interface ExperienceItem {
  id: string
  role: string
  company: string
  period: string
  scope: string
  highlights: string[]
  stack: string[]
}

export interface SkillGroup {
  id: string
  label: string
  skills: string[]
}

export interface ProjectLink {
  label: string
  href: string
}

/** A screenshot with responsive sources generated by scripts/optimize-images.mjs. */
export interface ProjectImage {
  /** Fallback src (960w WebP). */
  src: string
  width: number
  height: number
  /** `srcset` strings per format. */
  avifSrcSet: string
  webpSrcSet: string
  /** Tiny base64 placeholder shown while the image loads. */
  lqip: string
}

export interface Project {
  id: string
  title: string
  role: string
  period?: string
  summary: string
  highlights: string[]
  tags: string[]
  links: ProjectLink[]
  images: ProjectImage[]
  accent: AccentToken
}
